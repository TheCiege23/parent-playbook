-- Re-binding a browser's push subscription to whoever is signed in on it now.
--
-- push_subscriptions.endpoint is UNIQUE, and an endpoint belongs to the BROWSER and the
-- VAPID key — not to whoever is signed in. On a device two parents share, the second one
-- to turn reminders on collided with the first one's row. ps_insert refuses to write a row
-- for another user, ps_delete only reaches your own rows, and there is no update policy at
-- all, so the second parent had no way to take the endpoint and no way to be told why.
--
-- The application side of this already landed: logging out now deletes your own row and
-- unsubscribes the browser, which covers the ordinary case. It does not cover a session
-- that was simply abandoned — the tab closed, the token left to expire — and that row then
-- sits there indefinitely, silently swallowing the next person's reminders while the
-- departed parent's weekly push keeps arriving on a device somebody else is holding.
--
-- ---------------------------------------------------------------------------------------
-- Why this is safe, and what it deliberately does NOT allow.
--
-- The obvious design is "whoever presents the endpoint may claim it". That is what most
-- web-push implementations do, and it is too weak here: an endpoint can leak into a log or
-- an error report, and anyone holding one could then unbind the real owner (their reminders
-- stop) and have their own pushes delivered to that person's device instead. No data is
-- read either way, but it is an avoidable denial and an avoidable channel for unsolicited
-- content on a stranger's lock screen.
--
-- So a claim requires the FULL subscription: endpoint plus both keys. p256dh and auth are
-- generated by the push service for that subscription and are what a sender needs to
-- encrypt to it. A browser that still holds the subscription reports all three unchanged
-- through getSubscription(), whoever is signed in — which is exactly the shared-device case
-- and nothing else. Someone who has only observed an endpoint cannot produce the keys, and
-- someone who has all three could already push to that browser directly, so this conveys no
-- capability they did not already have.
--
-- SECURITY DEFINER because the whole point is to delete a row that RLS will not let the
-- caller delete. That makes the checks in the body the only gate, so they are explicit:
-- authenticated or nothing, all three values present, and the keys must match the row being
-- displaced. search_path is pinned empty and every name is schema-qualified.
create or replace function public.claim_push_subscription(
  p_endpoint text,
  p_p256dh   text,
  p_auth     text
) returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid   uuid := auth.uid();
  v_owner uuid;
begin
  if v_uid is null then
    raise exception 'a push subscription can only be claimed by a signed-in guardian'
      using errcode = '42501';
  end if;

  if p_endpoint is null or length(p_endpoint) = 0 or length(p_endpoint) > 2048
     or p_p256dh is null or length(p_p256dh) = 0 or length(p_p256dh) > 512
     or p_auth is null or length(p_auth) = 0 or length(p_auth) > 512 then
    raise exception 'endpoint and both subscription keys are required'
      using errcode = '22023';
  end if;

  select ps.user_id into v_owner
    from public.push_subscriptions ps
   where ps.endpoint = p_endpoint;

  -- Nobody holds it. This is the ordinary first subscribe, and it is the same row
  -- ps_insert would have allowed the caller to write for themselves.
  if v_owner is null then
    insert into public.push_subscriptions (user_id, endpoint, p256dh, auth)
    values (v_uid, p_endpoint, p_p256dh, p_auth);
    return true;
  end if;

  -- Already ours. Refresh the keys in case the push service rotated them, and say yes.
  if v_owner = v_uid then
    update public.push_subscriptions ps
       set p256dh = p_p256dh, auth = p_auth
     where ps.endpoint = p_endpoint;
    return true;
  end if;

  -- Held by someone else. Displace it only on proof the caller holds this subscription.
  delete from public.push_subscriptions ps
   where ps.endpoint = p_endpoint
     and ps.p256dh = p_p256dh
     and ps.auth = p_auth;

  if not found then
    -- The keys did not match, so the caller has an endpoint they do not hold. Report it
    -- rather than raising: the app tells the parent their reminders are not on, which is
    -- true, instead of showing them a database error they can do nothing about.
    return false;
  end if;

  insert into public.push_subscriptions (user_id, endpoint, p256dh, auth)
  values (v_uid, p_endpoint, p_p256dh, p_auth);
  return true;
end;
$$;

comment on function public.claim_push_subscription(text, text, text) is
  'Binds a browser push subscription to the calling guardian. Takes it from another guardian only when the caller supplies the subscription''s own p256dh and auth keys, which only the browser holding it has. Returns false rather than raising when the keys do not match.';

-- A SECURITY DEFINER function is executable by PUBLIC unless told otherwise, and PUBLIC
-- includes anon. Revoke first, then grant the one role that should have it.
revoke all on function public.claim_push_subscription(text, text, text) from public;
revoke all on function public.claim_push_subscription(text, text, text) from anon;
grant execute on function public.claim_push_subscription(text, text, text) to authenticated;
