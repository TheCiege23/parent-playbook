// Writes tools/adult-harness/index.html from index.html's own script list, so the harness loads exactly the app the
// site loads, in the same order, with three differences: the Supabase CDN script is replaced by fake-supabase.js, the
// Sentry loader and the marketing landing script are left out, and the service worker is not registered. Run from the
// repository root: node tools/adult-harness/build.cjs
//
// To use it: serve the repository root over HTTP (python -m http.server 8792) and open
// http://localhost:8792/tools/adult-harness/index.html. It opens Your training for a synthetic parent with Adult
// Training and no child; add ?scenario=family for a parent with one synthetic child against a database shaped like
// production today (unapplied migrations answer as missing). window.__harness.db holds every row the screens write,
// and "Start again" resets it. It is
// never deployed (the Dockerfile copies tools/ file by file) and never packaged.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..', '..');
const index = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const LEFT_OUT = ['/js/landing.js'];
const scripts = [...index.matchAll(/<script src="(\/js\/[a-z0-9-]+\.js)"><\/script>/g)].map(m => m[1]).filter(s => !LEFT_OUT.includes(s));
const styles = [...index.matchAll(/<link rel="stylesheet" href="(\/css\/[a-z0-9-]+\.css)" \/>/g)].map(m => m[1]).filter(s => s !== '/css/landing.css');
// The fake is loaded with a content hash in its URL, so a browser never runs a stale copy after it changes.
const fakeVersion = require('node:crypto').createHash('sha256').update(fs.readFileSync(path.join(__dirname, 'fake-supabase.js'))).digest('hex').slice(0, 12);
const fonts = (index.match(/<link href="https:\/\/fonts\.googleapis\.com\/css2\?[^"]+" rel="stylesheet" \/>/) || [''])[0];

const tags = [];
for (const src of scripts) {
  if (src === '/js/core.js') tags.push(`<script src="/tools/adult-harness/fake-supabase.js?v=${fakeVersion}"></script>`);
  tags.push(`<script src="${src}"></script>`);
  // pwa.js defines registerServiceWorker, which init.js calls at once. A harness on localhost must not install the
  // site's service worker, or its cache would serve stale files to the next local session.
  if (src === '/js/pwa.js') tags.push('<script>registerServiceWorker = function(){}; releasePushOnThisDevice = async function(){};</script>');
}

const html = `<!doctype html>
<!-- GENERATED by tools/adult-harness/build.cjs from index.html. Do not edit by hand; rebuild after index.html changes. -->
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
<meta name="robots" content="noindex" />
<title>Adult Training harness · synthetic data, not production</title>
${fonts}
${styles.map(s => `<link rel="stylesheet" href="${s}" />`).join('\n')}
<style>
  #harnessBar{position:fixed;left:0;right:0;bottom:0;z-index:9999;background:#3b1f00;color:#ffe7c2;font:12px/1.4 system-ui,sans-serif;padding:6px 10px;display:flex;gap:10px;align-items:center;justify-content:space-between}
  #harnessBar button{font:inherit;background:#ffe7c2;color:#3b1f00;border:0;border-radius:6px;padding:3px 8px}
</style>
</head>
<body>
<div id="appbg"></div>
<div id="appveil"></div>
<div id="harnessBar" role="note"><span>Local harness · synthetic in-memory data · nothing reaches production</span><button type="button" onclick="location.reload()">Start again</button></div>
<!-- Not hidden: on the site js/landing.js reveals #root when a visitor enters the app, and the harness leaves that script out. -->
<div class="wrap" id="root"></div>
<script>
  // ?scenario=family opens the synthetic child's week, against a database shaped like production today. Otherwise it
  // opens Your training for the synthetic account, which has Adult Training and no child profile.
  history.replaceState(null, '', location.pathname + location.search + (new URLSearchParams(location.search).get('scenario') === 'family' ? '#week' : '#adult'));
</script>
${tags.join('\n')}
</body>
</html>
`;
fs.writeFileSync(path.join(__dirname, 'index.html'), html);
console.log('wrote tools/adult-harness/index.html with ' + scripts.length + ' app scripts');
