// Guards on what the buyer package contains and what its one command promises.
//
// These are packaging invariants, not behaviour: the acceptance tool itself is
// exercised by running it against a built package (see the commit that added it),
// because a tool that reports on a package can only be tested by giving it one.
// What is checked here is the set of mistakes that would be invisible until a
// buyer hit them.
const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const { BUNDLE_FILES, BUNDLE_VERIFICATION, BUNDLE_CONTRACT_TESTS } = require('../tools/sdk-files.cjs');

test('the package ships the tools its own instructions tell a buyer to run', () => {
  for (const tool of ['tools/acceptance.cjs', 'tools/package-scan.cjs', 'tools/sdk-verify.cjs', 'tools/sdk-host.cjs']) {
    assert.ok(BUNDLE_VERIFICATION.includes(tool), `${tool} must be bundled`);
    assert.ok(BUNDLE_FILES.includes(tool), `${tool} must reach BUNDLE_FILES`);
  }
});

test('the live-identifier list is never bundled', () => {
  // package-scan.cjs reads this file to know what must not be packaged. Packaging the
  // list would publish exactly those identifiers — the scanner would leak what it guards.
  const list = 'tools/package-scan-identifiers.json';
  assert.ok(fs.existsSync(path.join(root, list)), 'the identifier list should exist in the source repository');
  assert.ok(!BUNDLE_FILES.includes(list), 'the identifier list must not be bundled');
});

test('no bundled file carries a live record identifier', () => {
  // The build-time gate. The shipped scanner cannot run this rule (it has no list), so
  // this is the check that actually protects a release.
  const { identifiers } = require('../tools/package-scan-identifiers.json');
  assert.ok(identifiers.length > 0, 'the identifier list should not be empty');
  const offenders = [];
  for (const name of BUNDLE_FILES) {
    if (name === 'README.md') continue; // generated by the bundler, not read from disk
    const file = path.join(root, name);
    if (!fs.existsSync(file)) continue;
    const bytes = fs.readFileSync(file);
    if (bytes.subarray(0, 4096).includes(0)) continue;
    const text = bytes.toString('utf8');
    for (const [needle, label] of identifiers) {
      if (text.includes(needle)) offenders.push(`${name} contains ${label} (${needle})`);
    }
  }
  assert.deepStrictEqual(offenders, [], 'bundled files must not reference live records');
});

test('every bundled contract test is bundled with its own file', () => {
  assert.ok(BUNDLE_CONTRACT_TESTS.length > 0, 'the package should ship runnable contracts');
  for (const name of BUNDLE_CONTRACT_TESTS) {
    assert.ok(fs.existsSync(path.join(root, name)), `${name} is listed but missing`);
    assert.ok(BUNDLE_FILES.includes(name), `${name} is listed but does not reach BUNDLE_FILES`);
  }
  // body-insights.test.cjs looked shippable by inspection and was not: it reaches for
  // app files the package does not carry, and shipping it produced seven failures in an
  // extracted package. Membership is decided by running the suite inside a built
  // package, never by reading require() lines.
  assert.ok(!BUNDLE_CONTRACT_TESTS.includes('tests/body-insights.test.cjs'),
    'body-insights.test.cjs needs unshipped app files; it cannot run inside the package');
});

test('the acceptance tool keeps stating what a clean run does not establish', () => {
  const { NOT_ESTABLISHED } = require('../tools/acceptance.cjs');
  assert.ok(Array.isArray(NOT_ESTABLISHED) && NOT_ESTABLISHED.length >= 5,
    'the honesty block must not be emptied out');
  const joined = NOT_ESTABLISHED.join(' ').toLowerCase();
  // 'substitution' rather than 'unsigned': signing now exists, so the block no longer says
  // the manifest is unsigned unconditionally — but it must still name the thing a checksum
  // cannot do, and must still say authenticity is unestablished without an independent key.
  for (const subject of ['accuracy', 'composition', 'dexa', 'restore', 'substitution', 'authenticity']) {
    assert.ok(joined.includes(subject), `the honesty block should still cover: ${subject}`);
  }
});

test('the handover does not send a buyer to a command that cannot run in the package', () => {
  // It previously did. `node --test "tests/*.test.cjs"` inside the package matched no
  // files, reported "tests 0" and exited 0 — a green result that verified nothing.
  const handover = fs.readFileSync(path.join(root, 'HANDOVER.md'), 'utf8');
  assert.ok(!/node --test "tests\/\*\.test\.cjs"/.test(handover),
    'HANDOVER.md must not tell a buyer to run a glob that matches nothing in the package');
  assert.ok(handover.includes('node tools/acceptance.cjs'),
    'HANDOVER.md should lead with the one command');
});
